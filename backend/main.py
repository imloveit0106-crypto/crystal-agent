# ==================== Conversation History Buffer ====================
# In-memory conversation history (use Redis/DB in production)
conversation_history = {}  # {user_id: [{"role": "user", "content": "..."}, {"role": "assistant", "content": "..."}]}
MAX_HISTORY_TURNS = 5  # Keep last 5 conversation turns (5 user + 5 assistant = 10 messages)


def add_to_history(user_id: str, role: str, content: str):
    """Add a message to conversation history"""
    if user_id not in conversation_history:
        conversation_history[user_id] = []

    conversation_history[user_id].append({
        "role": role,
        "content": content
    })

    # Keep only the last MAX_HISTORY_TURNS * 2 messages
    if len(conversation_history[user_id]) > MAX_HISTORY_TURNS * 2:
        conversation_history[user_id] = conversation_history[user_id][-(MAX_HISTORY_TURNS * 2):]


def get_history(user_id: str) -> list:
    """Get conversation history for a user"""
    return conversation_history.get(user_id, [])


# ==================== Request/Response Models ====================

class ChatMessage(BaseModel):
    """Chat message request model"""
    message: str
    user_id: Optional[str] = "default_user"


class ChatResponse(BaseModel):
    """Chat response model"""
    response: str
    type: str
    emotion: str
    amount: Optional[float] = None


# ==================== Streaming Helper Functions ====================

async def stream_gemini_response(
    user_message: str,
    context: dict
) -> AsyncGenerator[str, None]:
    """
    Stream AI response from Gemini in real-time.

    This function yields chunks of text as they are generated by Gemini,
    enabling a typewriter effect on the frontend.

    Args:
        user_message: User's input message
        context: Context dict with user profile, recent logs, etc.

    Yields:
        JSON strings containing text chunks in SSE format
    """
    if not ai_brain:
        # Fallback for demo mode
        demo_response = "Hello! This is a demo response. The AI is not configured yet."
        for char in demo_response:
            yield f"data: {json.dumps({'chunk': char, 'done': False})}\n\n"
            await asyncio.sleep(0.02)  # Simulate typing speed
        yield f"data: {json.dumps({'chunk': '', 'done': True})}\n\n"
        return

    try:
        # Use Gemini's streaming capability
        import google.generativeai as genai

        # Build the prompt with context
        prompt = ai_brain._build_prompt(user_message, context)

        # Get streaming response from Gemini
        model = genai.GenerativeModel(Settings.AI_MODEL)
        response = model.generate_content(prompt, stream=True)

        # Stream each chunk as it arrives
        for chunk in response:
            if chunk.text:
                # Send chunk in SSE format
                yield f"data: {json.dumps({'chunk': chunk.text, 'done': False})}\n\n"

        # Send completion signal
        yield f"data: {json.dumps({'chunk': '', 'done': True})}\n\n"

    except Exception as e:
        # Send error in SSE format
        error_msg = f"Error generating response: {str(e)}"
        yield f"data: {json.dumps({'error': error_msg, 'done': True})}\n\n"



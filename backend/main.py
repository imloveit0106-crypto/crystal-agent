@app.post("/api/chat")
async def chat(message: ChatMessage) -> ChatResponse:
    """
    Standard chat endpoint (non-streaming).
    Use /api/chat/stream for real-time streaming.
    """
    # Analyze the message
    analysis = text_analyzer.analyze(message.message)
    detected_type = analysis.get('type', '日記')
    detected_emotion = analysis.get('emotion', '普通')
    detected_amount = analysis.get('amount')

    # Get context
    context = {}
    profile = local_storage.get_user_profile()
    if profile:
        context['profile'] = profile

    ai_context = context_engine.get_context_for_ai(message.message, context.get('profile'))
    context.update(ai_context)

    # Add conversation history to context
    history = get_history(message.user_id)
    if history:
        context['conversation_history'] = history

    # Generate response
    if ai_brain:
        response_text = ai_brain.generate_response(message.message, context)
    else:
        response_text = "AI not configured. Please set GEMINI_API_KEY in .env file."

    # Save to conversation history
    add_to_history(message.user_id, "user", message.message)
    if response_text:
        add_to_history(message.user_id, "assistant", response_text)

    # Save to local storage
    local_storage.add_life_log(
        content=message.message,
        type_=detected_type,
        amount=detected_amount,
        emotion=detected_emotion
    )

    return ChatResponse(
        response=response_text,
        type=detected_type,
        emotion=detected_emotion,
        amount=detected_amount
    )


@app.post("/api/chat/stream")
async def chat_stream(message: ChatMessage):
    """
    Streaming chat endpoint using Server-Sent Events (SSE).

    This endpoint streams AI responses in real-time, enabling a typewriter effect
    and ChatGPT-like experience on the frontend.

    Response format (SSE):
        data: {"chunk": "text", "done": false}
        data: {"chunk": "", "done": true}
    """
    import asyncio

    # Analyze the message
    analysis = text_analyzer.analyze(message.message)
    detected_type = analysis.get('type', '日記')
    detected_emotion = analysis.get('emotion', '普通')
    detected_amount = analysis.get('amount')

    # Send metadata first
    async def generate():
        # Send metadata
        metadata = {
            'type': 'metadata',
            'detected_type': detected_type,
            'detected_emotion': detected_emotion,
            'detected_amount': detected_amount
        }
        yield f"data: {json.dumps(metadata)}\n\n"

        # Get context
        context = {}
        profile = local_storage.get_user_profile()
        if profile:
            context['profile'] = profile

        ai_context = context_engine.get_context_for_ai(message.message, context.get('profile'))
        context.update(ai_context)

        # Add conversation history to context
        history = get_history(message.user_id)
        if history:
            context['conversation_history'] = history

        # Collect full response for history
        full_ai_response = ""

        # Stream the response
        async for chunk_data in stream_gemini_response(message.message, context):
            # Extract chunk text from SSE format
            if chunk_data.startswith("data: "):
                chunk_json = json.loads(chunk_data[6:])
                if chunk_json.get('chunk') and not chunk_json.get('done'):
                    full_ai_response += chunk_json['chunk']

            yield chunk_data

        # Save user message to conversation history
        add_to_history(message.user_id, "user", message.message)

        # Save AI response to conversation history
        if full_ai_response:
            add_to_history(message.user_id, "assistant", full_ai_response)

        # Save to local storage after streaming completes
        # (In production, this should be non-blocking)
        local_storage.add_life_log(
            content=message.message,
            type_=detected_type,
            amount=detected_amount,
            emotion=detected_emotion
        )

    return StreamingResponse(
        generate(),
        media_type="text/event-stream",
        headers={
            "Cache-Control": "no-cache",
            "Connection": "keep-alive",
            "X-Accel-Buffering": "no"  # Disable nginx buffering
        }
    )


